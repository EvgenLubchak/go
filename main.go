package main

import (
	"bytes"
	"log"

	"github.com/hajimehoshi/ebiten/v2"
	etext "github.com/hajimehoshi/ebiten/v2/text/v2"
	"golang.org/x/image/font/gofont/goregular"
)

// [GO: КОНСТАНТИ ПАКЕТУ ВИДНО У ВСІХ ЙОГО ФАЙЛАХ]
//
// Ручки роз'їхались по трьох файлах, і жодне місце використання від цього не змінилось:
//
//	tuning_world.go   розмір поля, фізика середовища, темп рівнів
//	tuning_combat.go  удар, віддача, ривок, ухилення, рух гравця
//	tuning_visual.go  ворс, кульки, відросток, пружина тіла, фон, віджети
//
// Тут лишились прапорці РЕЖИМІВ (var нижче) — те, що перемикають під час експериментів,
// а не підкручують як числа.

// [ТИПОВИЙ СТАН] Значення, з якими гра стартує.
//
// Константами, а не просто початковими значеннями змінних, бо їх читає ще й HUD: він
// показує лише те, що ВІДРІЗНЯЄТЬСЯ від типового (див. drawHUD). Доки типове було
// вписане літералом у двох місцях, зміна дефолту тихо ламала індикатор — він або
// світився завжди, або не світився ніколи.
const (
	gameTPSDefault      = 60    // темп: 60 тіків, м'якший до батареї й до GPU
	antiAliasDefault    = false // per-path AA вимкнено: його роботу робить суперсемплінг
	renderScaleDefault  = 1.5   // суперсемплінг: 2.25 пікселя буфера на екранний
	soundEnabledDefault = false // фоновий ритм вимкнено (панель Tab → звук)
)

// [GO: PACKAGE-LEVEL VAR + INIT]
// var на рівні пакету — існує весь час роботи програми.
// init() викликається автоматично до main() — завантажуємо шрифт один раз.
// soundEnabled можна змінити під час роботи програми (на відміну від const).
// [GO: VAR vs CONST] — var дозволяє умовні перевірки без попереджень лінтера.
var (
	fontFaceSource      *etext.GoTextFaceSource
	soundEnabled        = soundEnabledDefault // фоновий ритм: панель Tab, персиститься
	difficultyGrowth    = false               // false — складність не росте (для тренування AI)
	showWhiskers        = false               // показувати сенсори стін і обрану дію Learner-а
	showMetrics         = false               // показувати панель метрик навчання (крива reward/TD) — клавіша M
	showInput           = true                // [ВВЕДЕННЯ] віджет натиснутих напрямків у правому низу
	showFrustration     = false               // показувати теплову карту феромонів фрустрації
	pheromonesEnabled   = false               // вмикає феромони фрустрації (стигмергію); false = чистий Q-learning без слідів
	epsilonDecayEnabled = false               // ε: false = постійна (qEpsilonConst); true = автоспад max→min
	sharedBrain         = true                // true = всі учні ділять ОДНУ мережу (вулик-розум); false = кожен свою
	localSight          = true                // [POMDP] true = агент бачить гравця лише поблизу+по прямій; false = всевидющий
	aiPlayer            = false               // [SELF-PLAY] true = гравцем керує мозок-жертва (вчиться тікати); false = людина
	// [ТЕМП] Частота тіків. Перемикається на панелі (Tab → «Ігрові налаштування»).
	//
	// Це БЕЗПЕЧНО за побудовою, і причина варта запису: у грі НІДЕ немає реального часу.
	// Усі числа в КАДРАХ — dashWindup, кулдауни, каденція, горизонт γ, буфер. Тож
	// зниження TPS рівномірно сповільнює фізику, анімацію Й навчання: вони лишаються
	// синхронними між собою, змінюється тільки швидкість у секундах.
	//
	// Заміри теж не страждають: стенд крутиться безголово, без прив'язки до частоти.
	//
	// ⚠️ ЄДИНИЙ ВИНЯТОК — ЗВУК. Біт рахується в РЕАЛЬНИХ секундах (sixteenthSec у
	// sound.go), тож без поправки при 60 TPS гра йшла б удвічі повільніше, а ритм —
	// у тому самому темпі, і вони розʼїхались би. Тому BPM множиться на tpsScale().
	// Показово, що єдине місце з реальним часом — саме те, що не є симуляцією.
	gameTPS = gameTPSDefault

	// [РЕНДЕР] Згладжування КОЖНОГО ШЛЯХУ окремо. Панель Tab → «Графіка». Типово ВИМКНЕНО.
	//
	// Вимкнено не тому, що погано виглядає, а тому, що його роботу робить renderScale
	// нижче — і робить ширше: суперсемплінг згладжує ще й кульки з долонями, які
	// малюються трикутниками й повз цей прапорець проходили завжди. Тримати обидва
	// означало платити вісімкратні малювання у трафарет за картинку, яка вже є.
	//
	// Лишається приладом: увімкни й порівняй ціну на тому самому екрані, де FPS.
	//
	// ЩО РОБИТЬ EBITEN (vector/fill.go): кожен шлях малюється у трафарет ВІСІМ разів із
	// субпіксельними зсувами замість одного, і кожен отримує область в атласі, УДВІЧІ
	// ширшу, ніж без згладжування. Тобто ціна росте з КІЛЬКІСТЮ ШЛЯХІВ у кадрі.
	//
	// У нас 10 шляхів на юніта, тож 50 видимих юнітів це 500 шляхів → 4000 малювань у
	// трафарет проти 500. Саме тому просадка приходить У БОЮ: юніти збігаються в купу й
	// разом потрапляють у кадр, а поза боєм вони розмазані по світу, що вчетверо
	// більший за вікно. Це помітив Євген у грі — числа самі до цього не вели.
	//
	// Документація ebiten каже про це рівно одним рядком: «AntiAlias increases internal
	// draw calls and might affect performance».
	//
	// Альтернатива без цієї залежності — renderScale нижче.
	antiAlias = antiAliasDefault

	// [СУПЕРСЕМПЛІНГ] У скільки разів більший буфер, у який малюється світ.
	// Панель Tab → «Графіка».
	//
	// 1.0 = вимкнено. Більше — кожен піксель екрана усереднюється з кількох сусідніх у
	// збільшеному буфері: те саме згладжування, але ціною СТАЛОЮ. Одна текстура й одне
	// стискання, байдуже скільки юнітів у кадрі й чи вони б'ються — а саме
	// НЕСТАБІЛЬНІСТЬ per-path AA і була проблемою, не середнє значення.
	//
	// Заповнення росте як КВАДРАТ множника, тож 1.5 коштує 2.25 пікселя на екранний
	// проти 4 у подвійного — майже вдвічі дешевше, а користі вже майже стільки ж.
	// Звідси й дефолт: 1.5 — знайдена на око точка, де різкість є, а кадр тримається.
	//
	// Верхній щабель (×4) практичного сенсу не має і стоїть як ПРИЛАД: він ізолює чисте
	// ЗАПОВНЕННЯ від кількості викликів. Усе інше в кадрі лишається незмінним — ті самі
	// 500 шляхів, ті самі трикутники, — а пікселів стає в 16 разів більше. Просадка між
	// ×2 і ×4 вимірює рівно ціну пікселя, і в цьому вона цінніша за опис словами.
	renderScale = float32(renderScaleDefault)

	// sceneScale — масштаб, який ФАКТИЧНО вдалось виділити.
	//
	// Окремо від renderScale, бо запит і результат можуть розійтись: текстура має стелю
	// розміру, і beginScene спускається драбиною вниз, доки не влізе. Розбіжність видно
	// на HUD як «SS 4×→2×» — мовчазне заниження було б гіршим за саму відмову.
	//
	// Камера множить саме на ЦЕ число. Якби вона брала запит, а буфер виявився меншим,
	// світ намалювався б за межами буфера — тобто ми побачили б чорний екран замість
	// чесного «не влізло».
	sceneScale = float32(renderScaleDefault)

	friendlyFire = false // [БІЙ] true = свої теж шкодять своїм (рій проріджує себе) — для експериментів

	// [БІЙ] Кадрів невразливості після отриманого удару.
	//
	// Var, бо це головна ручка ТЕМПУ бою: вона задає стелю шкоди по цілі — 1000/45 ≈ 22
	// удари на 1000 тіків. А темп бою це водночас темп НАВЧАННЯ для агентів із
	// бойовою нагородою: стражник отримує ~5.5 подій на 1000 тіків, тобто ~165 за
	// розігрів у 30000 — проти 30000 у рою зі щільною нагородою. Різниця в 180 разів,
	// і саме вона, а не гіперпараметри, обмежує його навчання.
	impactInvuln = 45

	// [ЗАМІР] Заморозка політики (клавіша L). Вимикає навчання і ставить ε=0.
	//
	// Навіщо: без неї замір іде ПО РУХОМІЙ ЦІЛІ — ваги змінюються прямо під час
	// вимірювання, плюс 1% дій випадкові через qEpsilonConst. Тоді число відповідає
	// на змішане питання «якої якості політику архітектура встигла намацати», де
	// склеєні швидкість навчання і стеля якості. GRU у такому порівнянні наперед
	// у програші: ми самі занизили йому learning rate заради стабільності.
	// Із заморозкою політика детермінована й нерухома → міряємо саме ЯКІСТЬ.
	frozenPolicy = false

	// [DOUBLE DQN] Розчеплення «хто обирає» і «хто оцінює» в цілі Беллмана.
	// Клавіша 2; індикатор ddqn — у рядку конфігурації панелі метрик.
	//
	// Проблема, яку лікує: max по зашумлених оцінках систематично зміщений УГОРУ,
	// бо та сама мережа і обирає дію, і оцінює її — власний шум сам себе
	// підтверджує, а γ множить зсув на весь горизонт. Виміряно наживо на
	// стражнику: чесна рівновага r/(1−γ) ≈ −0.3 (r −0.003, γ0.99), а панель
	// показувала Q +0.5 — роздування ~+0.8, яке ще й РОСЛО з інтенсивністю побиття
	// (більше подій → ширше гуляють ваги → жирніший max). З подвійною ціллю дію
	// обирає ЖИВА мережа, а оцінює TARGET: шуми різні, помилка одного не
	// підтверджує іншу (van Hasselt, 2015).
	//
	// Дефолт false НАВМИСНО — дефолти не міняються до заміру. Прогнози
	// зареєстровані в roadmap ДО запуску: (1) Q стражника осідає до −0.3…0 і
	// перестає рости від побиття; (2) Q вбивці просідає з 8–9; (3) спам dodge —
	// відкрите питання, і обидві відповіді цінні.
	doubleDQN = true

	// [FLOW-FIELD] Режим показу поля (панель Tab циклює):
	//   0 = вимкнено, 1 = поле ДО СТОРОНИ ГРАВЦЯ, 2 = поле ДО ВОРОГІВ
	showFlowField = 0
)

func init() {
	src, err := etext.NewGoTextFaceSource(bytes.NewReader(goregular.TTF))
	if err != nil {
		log.Fatal("font load:", err)
	}
	fontFaceSource = src
}

func main() {
	// [НАЛАШТУВАННЯ] Користувацькі відхилення (settings.json) накладаються на
	// дефолти ДО створення світу; кожна доля файлу — гучний рядок у консолі.
	loadSettings()

	// [ВУЛИКИ] Реєстр створюємо ТУТ і віддаємо в newUnitsWithHive: вона його заповнить
	// по ходу створення юнітів, і далі мережі живуть незалежно від тіл.
	hive := map[string]*Net{}
	game := &Game{
		difficulty: 1.0,
		player:     newPlayer(), // див. player.go — щоб налаштування гравця було чим перевірити
		hive:       hive,
		units:      newUnitsWithHive(hive),
	}

	game.player.resetFur() // [ВОРС] стартове положення хутра

	// [SELF-PLAY] Даємо гравцю власний мозок-жертву (flee=true → reward за ВТЕЧУ).
	// Окрема ефемерна мережа: не зберігається (зберігаємо лише хижаків через saveBrains).
	if aiPlayer {
		game.player.Brain = NewBrain()
		game.player.Brain.flee = true
	}

	startBeat(1.0) // запускаємо аудіо перед стартом гри

	ebiten.SetWindowSize(screenWidth, screenHeight)
	ebiten.SetWindowTitle("Boids")
	ebiten.SetTPS(gameTPS)

	err := ebiten.RunGame(game)

	// [ЗБЕРЕЖЕННЯ] Вікно, закрите хрестиком або Cmd+Q, повертає з RunGame nil і
	// ОМИНАЄ ESC-гілку в Update — без цього рядка така сесія тихо губила все
	// навчання, і наступний запуск вантажив ПОЗАМИНУЛИЙ стан. Виглядало це як
	// «поведінка стрибнула після перезаходу», хоча стрибала вона назад у часі.
	// Після ESC це другий виклик поспіль — нешкідливо: ті самі ваги в ті самі файли.
	//
	// ⚠️ СТОЇТЬ ПЕРЕД log.Fatal НАВМИСНО. log.Fatal — це os.Exit(1), а він не
	// виконує ні defer, ні решту функції. Доки збереження було НИЖЧЕ перевірки
	// помилки, будь-яка відмова графіки (втрачений контекст, збій шейдера, драйвер)
	// губила всю сесію — тобто рівно той симптом, від якого цей виклик і писався,
	// на єдиній гілці, якої він не покривав.
	game.saveBrains()

	if err != nil && err != errExit {
		log.Fatal(err)
	}
}
