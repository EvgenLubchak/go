//
// Запуск:
//
//	BOIDS_BENCH=1 go test -run TestMemoryBench -v -timeout 60m
//
// Параметри через середовище (усі необовʼязкові):
//
//	BENCH_SEEDS=10     скільки прогонів на конфіг (незалежних, див. runBenchTrial)
//	BENCH_SET=sweep    набір конфігів: main = архітектури, sweep = горизонт памʼяті
//	BENCH_WARMUP=20000 тіків навчання перед заміром
//	BENCH_MEASURE=6000 тіків у кожному вікні заміру
//	BENCH_MOVING=1     1 = гравець рухається, 0 = стоїть
//	BENCH_ARENA=0      1 = прибрати стіни (для бойових замірів: лабіринт додає лише
//	                   навігаційну лотерею, а стражник стоїть і бʼється)
//	BENCH_SEEK=0       1 = гравець ШУКАЄ найближчого й атакує (для бойових замірів:
//	                   стражник стоїть, і випадкове блукання до нього не дійде)
//	BENCH_COMBAT=0     1 = увімкнути бій (респаун стенд ставить безкінечний сам).
//	                   Вимкнений за замовчуванням: усі записані базові лінії зняті
//	                   без бою, і тихо ввімкнути його означало б їх знецінити
//
// ЧОМУ ГРАВЕЦЬ РУХАЄТЬСЯ ЗА ЗАМОВЧУВАННЯМ. Ручний протокол вимагав стояти
// нерухомо — і це виявилось найгіршим можливим вибором: рій злипався на цілі,
// сліпих кадрів майже не лишалось, а ті, що були, — вироджені (мікрозатемнення
// в товкотнечі впритул). Памʼять у такому режимі просто не потрібна. Коли ж
// гравець їздить, рій наосліп ~90% часу — саме та задача, заради якої памʼять
// узагалі вводили.
// ==========================================================================

// benchCfg — одна конфігурація памʼяті для порівняння.
type benchCfg struct {
	name   string
	gru    bool    // useGRU
	frames int     // memFrames: скільки слотів стеку несуть історію
	skip   int     // stackSkip: кадрів між семплами
	units  int     // скільки учнів на полі (1 перевіряє гіпотезу «рій замінює памʼять»)
	gruLR  float32 // gruLearnRate; 0 = лишити поточний
	gamma  float32 // qGamma; 0 = лишити поточний
	gskip  int     // [RNN] важіль BPTT: раз на скільки кадрів GRU думає; 0 = 1
	askip  int     // [ПОВТОР ДІЇ] раз на скільки кадрів вирішує СТЕК-шлях; 0 = 1

	// [КОНТРОЛІ] Дві комірки-відповіді на питання «це поведінка чи пружина».
	// [СУПУТНИКИ] Скільки СКРИПТОВАНИХ переслідувачів союзної фракції додати на поле.
	//
	// Навіщо, і це не помічник, а виправлення МОДЕЛІ ЗАДАЧІ. Стенд досі ставив на поле
	// рівно один тип, і для рою це правильно — його задача про гравця. Для мисливця це
	// хибна модель: у ГРІ його ціль обирає nearestTargetFor, тобто найближчий ворог АБО
	// гравець, і союзники для нього такі самі цілі. Різниця вирішальна:
	//
	//	проти гравця      1.3 проти 5.0     наздогнати НЕМОЖЛИВО
	//	проти союзників   1.3 проти 1.4/1.6 можливо, і вони САМІ йдуть на ворогів
	//
	// Без них калібрування дало шість подій нагороди за 30000 кадрів — не малий сигнал,
	// а його відсутність. У грі ж мисливець живий і бʼється: це видно на екрані.
	//
	// Супутники СКРИПТОВАНІ (IsLearner=false), і саме тому вони не псують замір: без
	// Brain вони не потрапляють у знаменник «наосліп» і не додають своїх кадрів у chase.
	companions int

	untrained bool        // 0 розігріву + заморожена політика: мережа НІКОЛИ не вчилась
	noForce   bool        // brainForce = 0: мозок думає, але рішення не рухають тіло
	base      *UnitConfig // базовий конфіг типу; nil = ConfigLearner

	// [БАЛАНС] Перебивання балансних чисел; 0 = лишити конфігове/глобальне.
	invuln int // impactInvuln — головна ручка ТЕМПУ бою, отже й темпу навчання

	// [БІЙ] Вимикання бойових ознак. Не «увімкнути», а саме ВИМКНУТИ: у грі вони
	// обидві є, тож нульове значення поля = поведінка гри, і комірку описує лише те,
	// чим вона від гри ВІДРІЗНЯЄТЬСЯ.
	offDashOpen bool // слот 14: вікно покарання
	offDashAtMe bool // слот 15: телеграф замаху

	// [РОЗІГРІВ] Покомірково, 0 = глобальний BENCH_WARMUP.
	//
	// Потрібен саме покомірковий, а не окремі прогони: різниця між двома НОМІНАЛЬНО
	// ОДНАКОВИМИ комірками в різних прогонах становить ~1.2 пункту (зміряно), і на цій
	// шумовій підлозі я вже спіймався, оголосивши ефект у +2.4 пункту. Порівняння
	// всередині одного прогону цієї підлоги не має.
	warmup int

	speed  float32 // MaxSpeed типу. qClip масштабується автоматично
	sight  float32 // sightRange; 0 = лишити поточний
	indep  bool    // true = sharedBrain=false (у кожного юніта СВОЯ мережа)
	wander float32 // WanderStrength; 0 = лишити конфігове (у учнів воно теж 0)
}

// benchOut — те, що знімаємо з одного вікна заміру.
