	// ворсу — ВІДСТАВАННЯ: кулька щокадру підтягується до своєї точки під тілом лише на
	// частку шляху, тож принципово не встигає. З цього само собою виходить розгойдування
	// на поворотах і відкид назад при розгоні — нічого з цього не запрограмоване.
	//
	// Жорсткість НИЖЧА за ворсову (0.05): кульки важчі на вигляд і мусять теліпатись
