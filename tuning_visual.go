	// Довжина сегмента = furLen / furJoints, тож загальна довжина від furJoints не
	// залежить і крутиться окремо.
	furJoints = 14

	// [ВОРС] Товщина від кореня до кінчика: звуження робить ворсинку схожою на волосину,
	// а не на дріт. Було зашито 2 і 1.
	furWidthRoot = 2.0
	furWidthTip  = 1.0

	furStrands      = 8    // ворсинок на юніта (по одній на кожен напрямок dirs8)
	furLen          = 15.0 // базова довжина ворсинки (px)
	furStiffness    = 0.45 // 0..1: наскільки кінчик наздоганяє ціль за кадр (менше = довший шлейф)
