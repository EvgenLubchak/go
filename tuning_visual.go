	ballCount  = 2
	ballStiff  = 0.30 // 0..1: наскільки кулька наздоганяє свою точку за кадр
	ballOffX   = 2.5  // рознесення по горизонталі від центру тіла
	ballDrop   = 12.0 // наскільки нижче центру висить (пів корпуса = 12.5)
	ballRadius = 3.8

	// [ВІДРОСТОК] Щупальце з нижньої точки тіла: ланцюжок суглобів із кулькою на кінці.
	//
	// Той самий принцип, що у ворсі й кульок — ВІДСТАВАННЯ, — але з двома відмінностями,
	// які й дають «щупальцевий» вигляд:
	//
	//	1. кожен суглоб тягнеться за ПОПЕРЕДНІМ, а не за тілом. Тому хвиля йде вздовж
	//	   ланцюжка згори вниз, а не смикає всі точки одночасно;
	//	2. жорсткість ПАДАЄ вниз по ланцюжку (tentFalloff). Кінчик відстає сильніше за
	//	   основу, і з цієї різниці виникає S-подібний вигин на поворотах — його не треба
	//	   програмувати, він наслідок.
	//
	// Коліна дешеві: ворс уже тримає 16 точок відставання на юніта, відросток додає 3.
