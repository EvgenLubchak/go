	// цього відставання й виникає розвівання: рушив — ворс лягає назад, різко
	// повернув — хльоскає, спинився — осідає. Жодне з цих правил не запрограмоване.
	// [ВОРС] Корінь — не центр тіла, а ВЕРХ: ворс росте з «голови», як грива, а не
