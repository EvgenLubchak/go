package main

// ══════════════════════════════════════════════════════════════════════════
// СВІТ: розмір поля, фізика середовища, темп рівнів
//
// Те, що описує САМУ АРЕНУ, а не тих, хто на ній: розміри, тертя, стигмергія,
// ріст складності, ритм, частота перебудови flow-field.
//
// [GO: ЧОМУ ФАЙЛИ, А НЕ ПАПКА] Тека в Go — це ОКРЕМИЙ ПАКЕТ. Винести константи в
// підпапку означало б експортувати кожну (damping → tuning.Damping) і правити сотні
// місць використання. Файли ж у одній теці належать тому самому пакету, і константи
// видно між ними без жодного префікса — увесь порядок за нуль змін у коді.
// ══════════════════════════════════════════════════════════════════════════

const (
	screenWidth  = 1700
	screenHeight = 980

	// [КАМЕРА] Розмір СВІТУ — може бути більшим за вікно. Камера (camera.go) слідує за
	// гравцем і показує лише видиму частину. Фізика, boidMap, flow-field, спавни —
	// все працює у СВІТОВИХ координатах; screenWidth/Height — лише розмір вікна й HUD.
	worldWidth  = 3400
	worldHeight = 1960

	pixelSize = 25
	// [СКЛАД ПОЛЯ] Кількість ворогів більше НЕ тут: кожен тип несе своє поле Count,
	// а хто виходить на поле — список unitRoster (pixel.go). Так додати новий тип
	// = один рядок, і неможливо мовчки лишитись без переслідувачів.

	// Глобальна фізика — однакова для всіх типів ворогів.
	// Поведінка (швидкість, агресія, burst) — в UnitConfig у pixel.go.
	// [ФІЗИКА] Множник швидкості щокадру: 1 = без тертя, менше = гальмує.
	//
	// Довго стояло 1 (тертя немає), і це давало наслідок, який ми довго приймали за
	// поведінку. Мозок додає прискорення 0.3 за кадр при стелі швидкості 1.2 — без
	// тертя юніт, який розігнався на ціль, ФІЗИЧНО не може підлетіти й зупинитись:
	// щоб погасити швидкість, треба стільки ж кадрів прискорюватись назад. Він
	// завжди пролітає повз і закладає дугу.
	//
	// Саме це ми називали «кидком кобри» і вважали вивченою тактикою. Виявилось —
	// балістика: агент увесь час просто хотів до цілі й не вмів гальмувати. Форма
	// тіла (див. drawBody) це й показала: вигин дивився на гравця, поки юніт летів
	// повз нього.
	//
	// УВАГА, ТОРКАЄТЬСЯ БОЮ. Шкода рахується від ШВИДКОСТІ ЗБЛИЖЕННЯ
	// (impactSpeedFrac), тож тертя напряму впливає на те, як сильно б'ють удари й чи
	// взагалі спрацьовує поріг. Міняючи це число, перевіряй бій, а не лише вигляд.
	damping             = 0.95  // 0.95 — юніти можуть гальмувати й зависати біля цілі
	visionRadius        = 3     // радіус огляду в клітинках boidMap
	showDetectionCircle = false // показувати радіус огляду ворогів (true/false)

	// [СТИГМЕРГІЯ] Феромони фрустрації — рій лишає сліди в глухих місцях і обходить їх.
	frustrationDeposit = 1     // слід за ОДНЕ застрягання (тепер рідко → більший внесок)
	frustrationDecay   = 0.970 // затухання сліду щокадру (місце поступово «забувається»)
	frustrationRepel   = 0.05  // сила відштовхування від слідів
	frustrationRadius  = 3     // радіус сканування слідів навколо агента (клітинки)

	levelUpEvery   = 60 * 60 // кожні 10 секунд (60fps × 5)
	difficultyStep = 2       // наскільки зростає складність за рівень
	maxDifficulty  = 250.0   // стеля складності

	// Аудіо: темп зростає разом зі складністю
	baseBPM          = 90.0   // BPM на рівні 1
	maxBPM           = 5000.0 // стеля темпу
	bpmPerDifficulty = 24.0   // скільки BPM додається за одиницю difficulty

	// [FLOW-FIELD] Раз на скільки кадрів перебудовувати маршрутні поля.
	// Джерел багато й вони рухаються, тож троттлинг замість «при зміні клітинки».
	flowRebuildEvery = 6

	boidMapW = worldWidth / pixelSize  // клітинок по горизонталі (за СВІТОМ, не за екраном)
	boidMapH = worldHeight / pixelSize // клітинок по вертикалі
)
