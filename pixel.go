// переслідувачі МОВЧКИ зникали. Тепер кожен тип відповідає сам за себе.
var unitRoster = []UnitConfig{
	ConfigLearner,    // зелені: ворожий рій-переслідувач (baseline)
	ConfigKiller,     // червоні: вороги, що знають лабіринт (flow-field) + бойова нагорода
	ConfigAllyChaser, // блакитні: твої переслідувачі — перехоплюють рій
	ConfigAllyKiller, // фіолетові: твої вбивці — знають лабіринт, ідуть на ворога
	ConfigBoss,       // малиновий: ОДИНАК із власною мережею — єдиний, кому памʼять потрібна
	ConfigWarden,     // золотий: СТРАЖНИК — лише бойова нагорода, тримає місце
	ConfigHunter,     // помаранчеві: МИСЛИВЦІ — лише бій + наосліп + рухомі
}

// unitTotal — скільки всього ворогів дає поточний склад.
func unitTotal() int {
	n := 0
	for _, cfg := range unitRoster {
		n += cfg.Count
	}
	return n
}

// Pixel описує одну частинку — гравця або ворога.
type Pixel struct {
	X, Y       float32
	VelX, VelY float32 // velocity — вектор швидкості (куди і як швидко рухається)
	AccX, AccY float32 // acceleration — вектор прискорення (сума сил: alignment + chase)
	Aggression float32 // 0.0..1.0: для Boid — рандомний, для інших — 1.0
	HP, MaxHP  int
	HitTimer   int
	HitWall    bool // [RL] чи врізався у стіну цього кадру (сигнал штрафу для Brain)

	// [БІЙ] Кому належить юніт (свої не б'ють своїх, якщо friendlyFire=false).
	Faction int
	// [БІЙ] Кадри невразливості після отриманого удару. Без цього агенти, що
	// перекриваються, отримували б шкоду КОЖЕН кадр (миттєва смерть у купі).
	InvulnTimer int

	// [ВАГА] Опір відкиданню, з конфігу типу (0 = звичайний, 1 = нерухомий).
	KnockResist float32

	// [ВІДСІЧ] Частка імпульсу, яку отримує ЦЕЙ юніт, коли б'є сам; 0 = глобальний
	// knockbackRecoil. Персонально, бо відсіч — навʼязаний рух, а він псує нагороду
	// тим, хто вчиться НАБЛИЖАТИСЬ (див. коментар у tuning_combat.go).
	KnockRecoil float32

	// [РЕСПАУН] Скільки повернень лишилось (негативне = безкінечно) і власний пост,
	// куди повертатись. Пост, а не випадкова точка: для стражника «повернувся на своє
	// місце» — правильна поведінка, і гравцеві передбачувано.
	RespawnsLeft   int
	SpawnX, SpawnY float32

	// [БІЙ] Кадри «відльоту» після зарахованого удару: поки > 0, стеля швидкості
	// піднята (knockSpeedMulti), інакше кліп MaxSpeed зʼїв би віддачу за один кадр.
	KnockTimer int

	// [УХИЛЕННЯ] Кадри активного ухилення (не прискорюється, невразливий) і кадри до
	// перезарядки. Живуть на Pixel, бо це стан ТІЛА, а не мозку: юніт може бути в
	// ухиленні й без мозку (напр. після рестарту), і фізика мусить це бачити.
	DodgeTimer    int
	DodgeRecover  int // [ВІДХІД] кадрів безпорадності після кидка (див. dodgeRecovery)
	DodgeCooldown int

	// [РИВОК] Стан машини фаз атаки: замах → ривок → відхід. Живе на Pixel, а не на
	// Game, хоч ривок поки лише в гравця: так симетричний варіант (юніти теж
	// замахуються, через девʼяту дію мозку) стає дописуванням, а не переносом.
	//
	// DashDirX/Y замикаються в момент ПОЧАТКУ замаху й далі не змінюються — саме це
	// робить атаку читабельною. Якби напрямок обирався в момент випуску, гравець
	// дивився б, куди відійшов юніт, і націлювався туди: вийшло б вгадування
	// «камінь-ножиці-папір», у якому оптимальна політика випадкова, а не реакція.
	DashPhase          int
	DashTimer          int
	DashDirX, DashDirY float32
	// [ВОРС] Позиції суглобів кожної ворсинки у СВІТОВИХ координатах:
	// Fur[ворсинка][суглоб][x,y], суглоб 0 = середина, 1 = кінчик.
	// Світові (а не локальні) саме тому, що відставання має бути від РУХУ юніта.
	Fur [furStrands][furJoints][2]float32

	// [КУЛЬКИ] Позиції кульок у СВІТОВИХ координатах — так само, як ворс. Світові, а не
	// локальні, саме тому, що відставання має бути від РУХУ юніта: локальні координати
	// рухались би разом із тілом і не відставали б ні від чого.
	Balls [ballCount][2]float32

	// [КІНЦІВКИ] Кінчики рук і ніг у СВІТОВИХ координатах — з тієї ж причини, що ворс,
	// кульки й щупальце: відставання має бути від РУХУ юніта.
	Limbs [limbCount][2]float32

	// [ЖАЛО] Лічильник пострілу відростка й ЗАМОРОЖЕНИЙ напрямок удару.
	//
	// Один лічильник на обидві фази: активна, поки StingTimer > stingCooldown, далі
	// перезарядка. Стан «наполовину вистрілив» недосяжний за побудовою.
	StingTimer           int
	StingDirX, StingDirY float32

	// [УДАР] Лічильник білого спалаху НАПАДНИКА — дзеркало HitTimer, який світить
	// ЖЕРТВІ. Окреме поле, а не спільне: події різні й тривалості в них свої.
	StrikeTimer int

	// [ВІДРОСТОК] Суглоби щупальця у СВІТОВИХ координатах — з тієї ж причини, що ворс
	// і кульки: відставання має бути від РУХУ юніта.
	//
	// Розмір — СТЕЛЯ (tentJointsMax), а справжня довжина ланцюжка в tentJointsOf(p):
	// вона своя в кожного типу. Масив, а не слайс, і це не смак:
	//
	//	1. Pixel лежить у g.units []Pixel ЗНАЧЕННЯМИ, тож масив сидить inline — нуль
	//	   алокацій і нуль розіменувань на кадр. Слайс дав би по алокації на юніта й
	//	   стрибок у купу на кожен доступ, а ці цикли крутяться щокадру на всіх юнітах;
	//	2. масив копіюється ПО ЗНАЧЕННЮ. Тести саме на це й спираються (`before := u.Tent`
	//	   перед кроком фізики). Зі слайсом той рядок став би аліасом на ту саму памʼять,
	//	   порівняння «до і після» тихо перетворилось би на порівняння з собою, і тест
	//	   лишився б зеленим, перевіряючи ніщо.
	Tent [tentJointsMax][2]float32

	// [ОЧІ] Зсув зіниці від центра ока, у частках pupilShift (−1..1 по кожній осі).
	// Не світові координати, на відміну від ворсу й кінцівок: око мале, і зберігати
	// абсолютну позицію означало б перераховувати її щоразу, коли тіло стиснулось.
	Pupil [2]float32

	// [РОТ] Наскільки розкритий: 0 = зібраний, 1 = витрачений. Лагається, як усе інше.
	Mouth float32

	// [ТІЛО] Стан пружини розміру: поточний масштаб і його швидкість. Пульс медузи
	// виникає з перельоту цієї пружини, а не з намальованого циклу.
	BodyScale float32
	BodyVel   float32

	Color color.RGBA
	Cfg   UnitConfig // конфіг типу (порожній для гравця)
	Brain *Brain     // нейронна мережа (nil для звичайних ворогів, не nil для Learner)
}

// resetFur миттєво ставить ворс у спокійне положення навколо юніта.
// Потрібно при спавні/респавні/рестарті — інакше ворс «прилетів» би через пів
// карти з попередньої позиції (лаг чесно відпрацював би телепорт).
func (p *Pixel) resetFur() {
	p.BodyScale, p.BodyVel = 1, 0

	cx := p.X + pixelSize/2
	cy := p.Y + pixelSize/2
	fx, fy := furRoot(cx, cy, 1)
	seg := float32(furLen) / furJoints
	for i := 0; i < furStrands; i++ {
		dx, dy := dirs8[i][0], dirs8[i][1]
		for j := 0; j < furJoints; j++ {
			d := seg * float32(j+1)
			p.Fur[i][j][0], p.Fur[i][j][1] = fx+dx*d, fy+dy*d
		}
	}
	for i := 0; i < ballCount; i++ {
		bx, by := ballHome(i, cx, cy, 1)
		p.Balls[i][0], p.Balls[i][1] = bx, by
	}
	for i := 0; i < limbCount; i++ {
		lx, ly := limbHome(i, cx, cy, 1)
		p.Limbs[i][0], p.Limbs[i][1] = lx, ly
	}
	// Відросток на спавні висить прямо вниз від нижньої точки тіла.
	//
	// Заповнюємо ВСЮ стелю, а не лише tentJointsOf(p): слоти за межами ланцюжка цього
	// типу ніхто не оновлює й не малює, але лишати в них нулі означає тримати точку в
	// (0,0) — а це вже пастка для будь-кого, хто колись підніме число суглобів у конфізі
	// або віддебажить масив цілком.
	rx, ry := tentRoot(cx, cy, 1)
	for i := 0; i < tentJointsMax; i++ {
		p.Tent[i][0], p.Tent[i][1] = rx, ry+tentSeg*float32(i+1)
	}
}

// limbSpec — де кріпиться кінцівка й куди звисає у спокої.
//
//	rx, ry  кут корпуса в частках півсторони (-1..+1)
//	dx, dy  напрямок звисання
//
// Руки з верхніх кутів ідуть униз-НАЗОВНІ, ноги з нижніх — майже прямо вниз. Саме ця
// різниця й читається як «руки» проти «ніг»: без неї виходять чотири однакові вусики.
var limbSpec = [limbCount]struct{ rx, ry, dx, dy float32 }{
	{-1, -1, -0.75, 0.66}, // ліва рука
	{+1, -1, +0.75, 0.66}, // права рука
	{-1, +1, -0.30, 0.95}, // ліва нога
	{+1, +1, +0.30, 0.95}, // права нога
}

// limbRoot — кут корпуса, з якого росте кінцівка i.
func limbRoot(i int, cx, cy, scale float32) (float32, float32) {
	sp := limbSpec[i]
	half := pixelSize / 2 * limbRootIn * scale
	return cx + sp.rx*half, cy + sp.ry*half
}

// limbHome — куди тягнеться кінчик кінцівки i у спокої.
//
// Окремою функцією з тієї ж причини, що ballHome, tentRoot і furRoot: потрібна у
// спавні, оновленні, малюванні й тесті, і розʼїхатись вони не мають права.
func limbHome(i int, cx, cy, scale float32) (float32, float32) {
	rx, ry := limbRoot(i, cx, cy, scale)
	sp := limbSpec[i]
	return rx + sp.dx*limbLen, ry + sp.dy*limbLen
}

// tentRoot — точка кріплення відростка: НИЗ тіла, а не центр.
//
// Окремою функцією з тієї ж причини, що ballHome: потрібна у спавні, оновленні й тесті,
// і розʼїхатись не має права — відросток, чий корінь на спавні інший, ніж в оновленні,
// смикнеться на першому ж кадрі.
func tentRoot(cx, cy, scale float32) (float32, float32) {
	return cx, cy + pixelSize/2*tentRootIn*scale
}

// furRoot — точка, з якої росте ворс: ВЕРХ тіла, а не центр.
//
// Окремою функцією з тієї ж причини, що ballHome і tentRoot: потрібна у спавні,
// оновленні, малюванні й тесті. Розʼїхатись вони не мають права — ворс, чий корінь у
// малюванні відрізняється від кореня в оновленні, візуально «відірветься» від тіла.
func furRoot(cx, cy, scale float32) (float32, float32) {
	return cx, cy - pixelSize/2*furRootUp*scale
}

// eyeRoot — центр ока i (0 = ліве, 1 = праве) у СВІТОВИХ координатах.
//
// Через ту саму пружину тіла (scale), що ворс, кінцівки й відросток: інакше при
// стисканні юніта обличчя лишилось би завеликим і читалось би як наклеєне.
func eyeRoot(i int, cx, cy, scale float32) (float32, float32) {
	dx := float32(eyeSpacing) / 2
	if i == 0 {
		dx = -dx
	}
	return cx + dx*scale, cy + float32(eyeOffsetY)*scale
}

// bodyScaleOf — поточний масштаб тіла з пружини (updateBody), із запобіжником для
// юнітів, створених в обхід resetFur (тести).
//
// [НАВІЩО ВСІМ КОРЕНЯМ] Тіло СТИСКАЄТЬСЯ на швидкості: bodySquash дає BodyScale ~0.78
// на повному ходу, тобто нижня грань малюється на ~2.75px вище. Кріплення, прибиті до
// СТАЛОЇ півсторони, за нею не встигали — і на швидкості щупальце візуально
// відривалось від корпуса. Ворс і кінцівки страждали так само, просто менш помітно.
//
// Тепер усі ЧОТИРИ кріплення множаться на цей масштаб і їдуть разом із намальованим
// тілом: furRoot, tentRoot, limbRoot і ballHome. Кульки приєднались останніми — їх
// пропустили, бо вони єдині не мають кореня в тілі й тому не виглядали «коренем».
func bodyScaleOf(p *Pixel) float32 {
	if p.BodyScale <= 0 {
		return 1
	}
	return p.BodyScale
}

// tentJointsOf — довжина ланцюжка щупальця ЦЬОГО юніта.
//
// Окремою функцією з тієї ж причини, що bodyScaleOf і ballHome: її питають три місця
// (фізика, малювання, тест), і розʼїхатись вони не мають права. Якби малювання й фізика
// брали різні числа, зайвий суглоб лишався б висіти там, де його ніхто не оновлює.
//
// Гравець сюди теж приходить: у нього Cfg порожній, тобто TentJoints == 0 → дефолт.
// Окремої гілки «якщо гравець» не потрібно — нуль її вже покриває.
//
// Обрізання до стелі — запобіжник від виходу за масив, а не робочий режим: перебір у
// складі поля ловить TestTentJointsFitTheArray.
func tentJointsOf(p *Pixel) int {
	n := p.Cfg.TentJoints
	if n <= 0 {
		n = tentJoints
	}
	if n > tentJointsMax {
		n = tentJointsMax
	}
	return n
}

// ballHome — точка, до якої тягнеться кулька i: під тілом, рознесені по горизонталі.
//
// Окремою функцією, бо її треба ТРИ рази (спавн, оновлення, тест), і розʼїхатись вони
// не мають права: кулька, чия домівка на спавні відрізняється від домівки в оновленні,
// на першому ж кадрі стрибне.
//
// scale — той самий множник пружини тіла, що у furRoot/tentRoot/limbRoot (bodyScaleOf).
// Кульки його довго НЕ мали, і це давало рівно ту хворобу, від якої лікували решту
// кріплень: домівка стояла на сталих 12px під центром, а нижня грань стиснутого тіла
// піднімалась до 9.75px — кріплення висіло на 2.25px НИЖЧЕ намальованого корпуса саме
// на швидкості, тобто рівно тоді, коли розрив і видно.
func ballHome(i int, cx, cy, scale float32) (float32, float32) {
	side := float32(2*i) - float32(ballCount-1) // для двох: -1 і +1
	return cx + side*ballOffX*scale, cy + ballDrop*scale
}

// reviveAt повертає юніта до життя на його посту.
//
// ОЖИВЛЯЄ той самий об'єкт разом із Brain — свідомо. Створити новий Brain було б
// простіше, але тоді метрики (m.agents ключується вказівником на Brain) рахували б
// кількість СМЕРТЕЙ замість кількості юнітів. Ми вже ловили це на рестартах.
//
// Памʼять агента при цьому СКИДАЄТЬСЯ: нове життя не має контексту минулого, і
// найважливіше — hasPrev=false, інакше наступна нагорода порівнювала б стан ПІСЛЯ
// відродження зі станом ПЕРЕД смертю й породила б безглуздий перехід через межу
// смерті.
func (p *Pixel) reviveAt(x, y float32) {
	p.X, p.Y = x, y
	p.VelX, p.VelY = 0, 0
	p.AccX, p.AccY = 0, 0
	p.HP = p.MaxHP
	p.InvulnTimer = 0
	p.HitTimer = 0
	p.KnockTimer = 0
	p.DodgeTimer, p.DodgeCooldown = 0, 0 // [УХИЛЕННЯ] нове життя — чиста перезарядка
	p.resetFur()
	if p.Brain != nil {
		p.Brain.resetForNewLife()
	}
}

// aggressionColor повертає колір від синього (пасивний) до червоного (агресивний).
func aggressionColor(a float32) color.RGBA {
	return color.RGBA{
		R: uint8(80 + 175*a),
		G: uint8(80 * (1 - a)),
		B: uint8(200 * (1 - a)),
		A: 255,
	}
}

// newUnits створює поле бою за unitRoster: кожен тип дає cfg.Count юнітів.
//
// [ДВА ВУЛИКИ] Типи мозку вчаться НЕЗАЛЕЖНО: у кожного своя спільна мережа і
// свій файл ваг. Тому зміна reward/входів для вбивці не чіпає тонко налаштований
// рій — і навпаки.
func newUnits() []Pixel { return newUnitsWithHive(nil) }

// newUnitsWithHive — те саме, але з можливістю ПЕРЕДАТИ вже наявні мережі.
//
// Навіщо: рестарт (клавіша R) мусить скидати СВІТ, а не мозки. Без цього кожне
// натискання R відкидало б усе навчання від початку сесії, бо newNetFor перечитує
// ваги з диска, а пишуться вони лише на виході й на game over. Для боса це було б
// смертельно: він і так вчиться у вісім разів повільніше за вулик, бо в нього немає
// спільного буфера досвіду.
//
// Передана мапа зберігає не лише ваги, а й БУФЕР ДОСВІДУ (він живе в Net) — а він
// набирається тисячі кадрів, і губити його на кожен рестарт означало б обнуляти
// найдорожче.
//
// nil = звичайний старт: мережі беруться з файлів.
// У режимі sharedBrain=false мапа не задіяна — там мережа в кожного своя, а тіла
// після рестарту нові.
func newUnitsWithHive(hive map[string]*Net) []Pixel {
	units := make([]Pixel, 0, unitTotal())

	// [ВУЛИКИ] У режимі sharedBrain агенти одного ТИПУ мозку (= одного файлу ваг)
	// ділять одну мережу. Мапа замість окремих змінних — щоб додати новий тип було
	// достатньо вказати йому WeightsFile, не чіпаючи цей код.
	if hive == nil {
		hive = map[string]*Net{}
	}
	hiveLoaded := map[string]bool{}
	for file := range hive {
		hiveLoaded[file] = true // передана мережа = вже навчена → ε-floor
	}
	netFor := func(file string, mem memContract, gamma, clip float32) (*Net, bool) {
		if !sharedBrain {
			return newNetFor(file, mem, gamma, clip) // кожен агент — власна мережа
		}
		if n, ok := hive[file]; ok {
			return n, hiveLoaded[file]
		}
		n, loaded := newNetFor(file, mem, gamma, clip)
		hive[file], hiveLoaded[file] = n, loaded
		return n, loaded
	}

	i := -1 // наскрізний номер юніта — для циклічного перебору спавн-точок
	for _, cfg := range unitRoster {
		for k := 0; k < cfg.Count; k++ {
			i++

			// Boid: колір і агресія рандомні. Інші: фіксований колір, агресія 1.0.
			// [GO: ZERO VALUE CHECK] cfg.Color.A == 0 → Color не виставлений → Boid
			aggression := float32(1.0)
			col := cfg.Color
			if col.A == 0 {
				aggression = rand.Float32()
				col = aggressionColor(aggression)
			}

			// Спавн — за ФРАКЦІЄЮ: свої з міток 'A', вороги з 'E' (level.go).
			// Якщо міток немає — випадкова відкрита клітинка.
			// [GO: MODULO] i%len(spawns) — циклічний перебір без виходу за межі.
			spawns := enemySpawns
			if cfg.Faction == factionPlayer {
				spawns = allySpawns
			}
			var spawnX, spawnY float32
			if len(spawns) > 0 {
				sp := spawns[i%len(spawns)]
				spawnX, spawnY = sp.X, sp.Y
			} else {
				for tries := 0; tries < 50; tries++ {
					spawnX = float32(rand.Intn(worldWidth - pixelSize))
					spawnY = float32(rand.Intn(worldHeight - pixelSize))
					if !isInteriorWallRect(spawnX, spawnY) {
						break
					}
				}
			}

			// [GO: POINTER = nil для звичайних ворогів]
			// Brain створюємо тільки для Learner (cfg.IsLearner). Тригер — прапорець,
			// НЕ мітка. У режимі sharedBrain усі вказують на спільну мережу; інакше —
			// кожен має власну (завантажену з файлу або нову).
			var brain *Brain
			if cfg.IsLearner {
				mem := resolveMemContract(cfg.Memory, cfg.MemFrames, cfg.StackSkip, cfg.GruSkip, cfg.ActSkip)
				gamma, clip := resolveHorizon(cfg.Gamma, cfg.QClip)
				net, loaded := netFor(cfg.WeightsFile, mem, gamma, clip)
				// [УТРИМАННЯ] Місткість кільця — властивість ТИПУ. Ставимо до першого
				// remember: після нього буфер уже виділено, і зміна розміру зламала б
				// індексацію по модулю.
				if cfg.ReplayCap > 0 && net.replay == nil {
					net.replayCap = cfg.ReplayCap
				}
				brain = NewBrainWith(net)
				brain.combat = cfg.CombatReward   // [БІЙ] бойові члени нагороди
				brain.combatOnly = cfg.CombatOnly // [РОЗРІДЖЕНА] без щільного «наближайся»
				brain.flowNav = cfg.UsesFlowField // [ВБИВЦЯ] прогрес міряємо вздовж коридору
				if loaded {
					brain.age = qEpsilonDecay // завантажена = навчена → ε-floor
				}
			}

			units = append(units, Pixel{
				X:           spawnX,
				Y:           spawnY,
				VelX:        (rand.Float32() - 0.5) * cfg.MaxSpeed,
				VelY:        (rand.Float32() - 0.5) * cfg.MaxSpeed,
				Aggression:  aggression,
				HP:          cfg.MaxHP,
				MaxHP:       cfg.MaxHP,
				Faction:     cfg.Faction, // [КОМАНДИ] сторона юніта
				KnockResist: cfg.KnockResist,
				KnockRecoil: cfg.KnockRecoil,

				// [РЕСПАУН] Пост, куди повертатись, і скільки повернень лишилось.
				SpawnX:       spawnX,
				SpawnY:       spawnY,
				RespawnsLeft: cfg.Respawns,
				Color:        col,
				Cfg:          cfg,
				Brain:        brain,
			})
			units[len(units)-1].resetFur()
		}
	}
	return units
}
