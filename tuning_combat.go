package main

// ══════════════════════════════════════════════════════════════════════════
// БІЙ: удар, віддача, ривок гравця, ухилення, рух гравця
//
// Найдорожчий блок у проєкті за кількістю виведених чисел. Майже кожна константа тут
// не підібрана на око, а ВИВЕДЕНА з геометрії або з умови «розв'язок існує» — і поруч
// лежить пояснення, звідки вона взялась і який замір її підтвердив.
//
// [GO: ЧОМУ ФАЙЛИ, А НЕ ПАПКА] Тека в Go — це ОКРЕМИЙ ПАКЕТ. Винести константи в
// підпапку означало б експортувати кожну (damping → tuning.Damping) і правити сотні
// місць використання. Файли ж у одній теці належать тому самому пакету, і константи
// видно між ними без жодного префікса — увесь порядок за нуль змін у коді.
// ══════════════════════════════════════════════════════════════════════════

const (

	// [БІЙ] Шкода від УДАРУ НА ШВИДКОСТІ («кидок кобри»).
	// Шкодить не сам дотик, а ЗБЛИЖЕННЯ на швидкості: беремо проєкцію швидкості
	// на напрямок до цілі (closing speed). Асиметрично — шкоду завдає той, хто
	// летить У іншого. Тому: повільно зіштовхнулись = нічого; налетів = вкусив;
	// лоб-у-лоб = обидва отримали. «Кидок і відступ» виникає САМ (після удару
	// швидкість витрачена → ти вразливий), його не треба програмувати.
	//
	// Поріг — ЧАСТКА власної максимальної швидкості, а не абсолют: гравець
	// (5.0 px/кадр) у ~6 разів швидший за учня (0.8), тож абсолютний поріг зробив
	// би гравця танком, а ворогів — безпечними. Плюс абсолютна підлога, щоб
	// повільні типи не вбивали «повзком».
	impactSpeedFrac = 0.6 // ≥60% власного максимуму в бік цілі → удар
	impactMinSpeed  = 0.4 // абсолютна підлога швидкості удару (px/кадр)
	impactDamage    = 1   // шкода за один удар
	playerMaxHP     = 20  // здоровʼя гравця (більше не вмирає з одного дотику)

	// [БІЙ] ВІДДАЧА КИДКА — окрема механіка від bodyBounce, і це принципово.
	//
	// bodyBounce пропорційний швидкості зіткнення: тиснуться на 0.3 — відскакують на
	// 0.3. Через це «кидком кобри» не пахло: юніти зіштовхувались і мікрорухами
	// намагались поглинути одне одного. Віддача ж спрацьовує ЛИШЕ коли удар
	// ЗАРАХУВАВСЯ, і вона фіксована й велика.
	//
	// Ключова деталь: updateUnits обрізає швидкість по MaxSpeed (1.2 у рою), тож
	// будь-який імпульс зʼїдався б кліпом уже наступного кадру. Тому на knockFrames
	// кадрів стеля піднімається в knockSpeedMulti разів — так само, як у файтингах
	// відлітають після удару.
	//
	// Дистанція відльоту ≈ imp × (1−damping^frames)/(1−damping). При 4.0 і 20 кадрах
	// це ~50px, тобто два корпуси: юніт мусить реально повертатись на нову атаку.
	knockbackImpulse = 5.0 // швидкість, з якою ЦІЛЬ відлітає від удару
	// [ВІДСІЧ] Частка імпульсу, яку отримує НАПАДНИК. ДЕФОЛТ — типи можуть мати свій
	// (UnitConfig.KnockRecoil), і це не зручність, а необхідність.
	//
	// Відсіч — це НАВʼЯЗАНИЙ рух: агент її не обирав. А progress, з якого росте щільна
	// нагорода «наближайся», рахується з ВЛАСНОЇ швидкості юніта. При 1.99 відсіч дає
	// до 2.4 швидкості проти brainForce 0.3 — увосьмеро більше за те, що агент реально
	// вирішує. Тобто нагорода за зближення значною мірою стає нагородою за те, що його
	// відкинуло.
	//
	// Це рівно та вада, через яку ми викинули WanderStrength: контрольний тест «чи міг
	// агент вплинути на це число сам?» відсіч не проходить. Separation ту саму перевірку
	// теж не проходив, але був 0.01 проти 0.3 — три відсотки, і замір показав, що це
	// нижче шумової підлоги. Тут вісімсот відсотків.
	//
	// ПРАВИЛО: висока відсіч — лише типам БЕЗ щільного члена «наближайся» (CombatOnly).
	// У них нагорода приходить тільки з бою, тож навʼязаний рух її не псує. Усі, хто
	// вчиться наближатись, лишаються на низькій.
	knockbackRecoil = 1.99
	knockFrames     = 60  // кадрів піднятої стелі швидкості
	knockSpeedMulti = 4.0 // у скільки разів піднімається стеля на цей час

	// [БІЙ] Пружність відбивання тіл одне від одного (1 = без втрат, як від стіни).
	// Діє і юніт↔гравець, і юніт↔юніт. ДРІБНА фізика дотику, не удару.
	//
	// Спершу тут було ПОГЛИНАННЯ (швидкість у бік гравця обнулялась) — і юніт
	// назавжди застрягав на поверхні: за кадр мозок додає лише brainForce 0.3, а
	// поріг удару 0.72 (у вбивці 0.96), тож розігнатись повторно він не встигав
	// НІКОЛИ. Удари перестали проходити взагалі.
	//
	// Відбивання дає рівно потрібний ритм: налетів → вкусив → відскочив → мусить
	// зайти знову. Розбігу треба мало (0.3 за кадр, повна швидкість за 4 кадри),
	// тож циклу вистачає кількох пікселів — але поки юніт просто тиснеться, він
	// відскакує зі своєю ж мізерною швидкістю й порогу не досягає.
	//
	// Темп шкоди при цьому впирається не в фізику, а в impactInvuln: 1 удар на 45
	// кадрів по цілі, скільки б юнітів не налітало. Балансувати треба ЙОГО.
	bodyBounce = 1.0

	hitFlashDuration = 17 // кадрів білого миготіння ЖЕРТВИ після удару

	// [УДАР] Кадрів білого спалаху НАПАДНИКА — світяться відросток і кульки.
	//
	// Коротший за hitFlashDuration навмисно: удар — це мить, а біль триває. Плюс
	// нападник у щільному бою бʼє часто, і довгий спалах злився б у постійне світіння,
	// тобто перестав би позначати подію.
	strikeFlashDuration = 10

	// [БІЙ: РИВОК] Єдина атака гравця. Замінила ульту (AoE радіусом 120 раз на 10
	// кадрів), яку ми видалили як таку, що ламає механіку: від неї НЕМОЖЛИВО було
	// ухилитись, тож вона перетворювала бій на молотіння, а не на позицію й таймінг.
	//
	// Три фази, як у бійках: ЗАМАХ (видно, напрямок замкнено) → РИВОК (шкода) →
	// ВІДХІД (керування заблоковане). Сенс не в тому, що гравець зупиняється, —
	// зупинка це побічний ефект. Сенс у тому, що ЛІНІЯ УДАРУ стає відомою за
	// dashWindup кадрів до удару, і в юніта з'являється що читати.
	//
	// ЗВІДКИ ЧИСЛА. Перші чотири ВИВЕДЕНІ, а не підібрані на око. Три доданки:
	//
	//	1. ГЕОМЕТРІЯ    корпус / швидкість = 25 / 0.6 = 41.7 кадру
	//	2. ε-ШУМ        частина кадрів іде на випадкову дію: ефективна швидкість
	//	                0.6 × (1 − ε×7/8) = 0.595 → 42.0 кадру
	//	3. ЗАТРИМКА     ознака замаху НАРОСТАЄ з нуля (на кадрі 5 з 45 сигнал лише
	//	                0.11), тож агент не може почати з кадру 0. Кладемо 25%.
	//
	//	42.0 / (1 − 0.25) = 56 кадрів
	//
	// Спершу тут стояло 45 — рівно перший доданок, і перевірка показала, що це
	// працює ЛИШЕ при нульовій затримці реакції: 45 кадрів дають 26.8px без затримки,
	// але 20.1px при 25%, тобто менше за корпус. Тобто ідеальна політика ще ухилилась
	// би, а будь-яка реальна — ні, і ми б виміряли нуль і знову шукали причину в
	// гіперпараметрах. Беремо 60 → 26.8px навіть при 25% затримки.
	//
	//   dashWindup   ≥ 56 — інакше УХИЛЕННЯ фізично неможливе (агент не встигає
	//                  зійти з лінії, і жодна політика не допоможе — саме на цьому
	//                  ми спалили чотири заміри: γ, горизонт, памʼять, темп);
	//   dashRecovery ≥ 56 — інакше неможливе ПОКАРАННЯ: агент, що відійшов на
	//                  корпус, не встигає повернутись, і «ідеальна» політика — вічно
	//                  тікати з нульовою нагородою. Пацифіст, а не боєць.
	//
	// dashActive обмежений ЗВЕРХУ, і це я спершу пропустив. Ривок несе гравця
	// dashActive × швидкість пікселів ЗА ціль, а стражник за відхід криє лише
	// dashRecovery × 0.595:
	//
	//	відліт − корпус ≤ dashRecovery × 0.595
	//	dashActive × 10 − 25 ≤ 35.7   →   dashActive ≤ 6
	//
	// При 10 було 100px відльоту проти 36px досяжності — покарання неможливе ФІЗИЧНО,
	// точно як ухилення при замаху 45. Замір це й показав: «завдано» впало з 1.7 до
	// 0.8, бо стражник більшість часу проводив далеко від гравця. Беремо 5 → відліт
	// 50px, треба закрити 25px при можливих 35.7.
	//
	// Ця ж межа задає benchDashRange: замахуватись треба БЛИЖЧЕ, ніж дістає ривок,
	// інакше він не доносить узагалі.
	//
	// При 120 TPS це 0.5с на фазу, 1.04с на повний цикл — швидка важка атака.
	//
	// dashDamage виведено з умови «ухилятись вигідніше, ніж розмінюватись». Юніт
	// ранить дотиком на швидкості, тобто заробляє НЕПЕРЕРВНО, поки тримається біля
	// гравця (стеля — один удар на impactInvuln). Отже за час між двома ривками він
	// заробляє tИМ БІЛЬШЕ, чим ця пауза довша:
	//
	//	заробіток за один цикл атаки:  impactDamage × dashCadence / impactInvuln
	//	втрата від пропущеного ривка:  dashDamage
	//
	// Ухилення вигідне лише якщо друге більше за перше.
	//
	// ⚠️ ТУТ Я ПОМИЛИВСЯ ДВІЧІ, ПЕРШ НІЖ ЗМІРЯТИ. Спершу взяв за каденцію мінімальний
	// цикл (100 кадрів) і отримав «dashDamage > 2.2, беремо 5, запас ×2.25». Потім
	// порівняв швидкості шкоди в РІЗНИХ часових базах і вирішив, що умова порушена.
	// Правильно — рахувати по СПРАВЖНІЙ каденції, і обидві сторони масштабуються з нею
	// разом:
	//
	//	1 × 230 / 45 = 5.1 заробітку   проти   5 втрати   →   умова НЕ виконувалась
	//
	// Тобто при dashDamage = 5 ми б виміряли розмінника, а не ухильника, і знову
	// списали б це на гіперпараметри. Беремо 8 → запас ×1.57.
	//
	// Це не баланс, а УМОВА ІСНУВАННЯ потрібного нам розвʼязку — того ж роду, що
	// dashWindup ≥ 42. Обидві перевірені тестами (TestDodgeIsPhysicallyPossible,
	// TestDodgingBeatsCamping), щоб тюнінг не зламав їх молча.
	dashWindup     = 60  // замах: напрямок замкнено, гравець стоїть (виведено: ≥56)
	dashActive     = 5   // ривок: шкода на контакті (5×10px = 50px, ≤6 за межею вище)
	dashRecovery   = 60  // відхід: керування заблоковане (виведено: ≥56)
	dashDamage     = 8   // шкода ривка (виведено: > impactDamage×dashCadence/impactInvuln)
	dashSpeedMulti = 2.0 // множник стелі швидкості на час ривка

	// dashCadence — ЗМІРЯНА середня пауза між ВЛУЧНИМИ ривками, у кадрах.
	//
	// Не dashCycle: між ривками гравець ще й повертається до цілі, а на цілі тікає
	// impactInvuln. Історія замірів (шкода на 1000 тіків ÷ dashDamage):
	//
	//	dashActive 10, замах 45:  21.7 / 5 = 4.34 влучань → 230 кадрів
	//	dashActive  5, замах 60:  42.0 / 8 = 5.25 влучань → 190 кадрів
	//
	// Коротший ривок лишає гравця поруч, тож і пауза коротша. Беремо 200 —
	// зміряні 190, округлені ВГОРУ: більша каденція робить умову вище СТРОГІШОЮ, отже
	// помилка в бік запасу.
	//
	// Живе константою саме тому, що від неї залежить та умова. Змінив dashActive,
	// швидкість гравця чи benchDashRange — переміряй, інакше умова тихо перестане
	// виконуватись.
	dashCadence = 200

	// [УХИЛЕННЯ] Окрема дія (actionDodge): коротке вікно невразливості + кулдаун.
	//
	// ЧОМУ ЧАСОВЕ, А НЕ ПОЗИЦІЙНЕ. Ухилення РУХОМ у нас безкоштовне — будь-який рух
	// ламає замкнений приціл, і зміряно, що навчання додає до цього 2% (невчений 34.0,
	// навчений 33.3). Оракул із поданою відповіддю теж нічого не дав (52%, p = 0.74).
	// Тобто задача не мала градієнта, а не була важкою.
	//
	// ЗВІДКИ ЧИСЛА:
	//
	//	dodgeInvuln 20   мусить накрити активну фазу ривка (dashActive = 5) із запасом
	//	                 на похибку таймінгу; 20 дає ±7 кадрів слабини
	//	dodgeCooldown 120 при каденції атак ~200 кадрів це ~1.7 спроби на ривок. Спам
	//	                 покриває 20/200 = 10% часу, точний таймінг — 100%. Дискримінація
	//	                 вдесятеро: саме те, чого бракувало ухиленню рухом
	//
	// ЦІНА ДІЇ, і без неї все ламається: поки триває ухилення, юніт НЕ ПРИСКОРЮЄТЬСЯ,
	// отже не набирає швидкості зближення й не може вдарити. Без цієї ціни «тиснути
	// щойно перезарядилось» було б слабко домінантною сталою політикою, і агент
	// отримав би 10% пом'якшення, нічого не вивчивши.
	dodgeInvuln   = 20
	dodgeCooldown = 120

	// [ВІДКИД] Ухилення не лише дає невразливість, а й ВІДКИДАЄ тіло — перпендикулярно
	// лінії загрози.
	//
	// НАВІЩО. Суто часове ухилення виявилось надто тонким: вікно спрацювання це
	// dodgeInvuln = 20 кадрів із циклу атак ~200, тобто 10% часу. Випадкове натискання
	// дає ті самі 10%, і зміряно, що навчений блокує лише 16% ривків — ледве вибиваючись
	// за випадковий рівень. Помилився на пʼять кадрів — і ривок прилетів, бо тіло
	// нікуди не поділось.
	//
	// ЗВІДКИ ЧИСЛА. Швидкість 3.0 із damping 0.95 і піднятою стелею дає шлях
	// 3.0 × (1 − 0.95^t)/0.05; корпус (25px) покривається за ~11 кадрів, за всі 20 —
	// 37.8px. Отже тиснути можна в останні ~49 кадрів замаху замість 20:
	//
	//	вікно 20 кадрів (10% циклу)  →  49 кадрів (25% циклу), у 2.5 раза ширше
	//
	// ЦІНА, І ЇЇ ТРЕБА ЗНАТИ: дискримінація падає з 10× до ~4×. Ми обмінюємо різкість
	// сигналу на легкість навчання — свідомо, бо зараз агент ледве вибивається за
	// випадок. Утримує від виродження кулдаун: при 120 кадрах на цикл у 200 той, хто
	// тисне абияк, у ~60% випадків буде на перезарядці саме тоді, коли прилетить ривок.
	dodgeDashSpeed = 3.0

	playerAccel     = 0.45 // прискорення при натисканні клавіші
	playerFriction  = 0.90 // тертя щокадру
	playerBaseSpeed = 5.0  // макс швидкість гравця на рівні 1
	playerTurnSpeed = 0.03 // [RAYCASTER] швидкість повороту камери (рад/кадр) у виді 1-ї особи
)
