// КАМЕРА: зум і стеження за гравцем у виді зверху.
//
// [ЧОМУ ТРАНСФОРМАЦІЯ В ТОЧКАХ ВИКЛИКУ, А НЕ МАСШТАБУВАННЯ КАРТИНКИ]
//
// Найпростіший спосіб — намалювати світ в окреме зображення й розтягнути його. Але
// тоді при зумі 2× ми РОЗТЯГУЄМО пікселі: ворсинка завтовшки 2px стає розмитою
// смугою 4px. У нас усе векторне, тож правильний шлях — перевести координати ДО
// малювання: та сама ворсинка малюється як 4px у власній роздільності й лишається
// різкою. Ціна — трансформувати в кожній точці виклику, і саме тому camera має
// короткі імена px/py/s: вони трапляються тридцять разів.
//
// [ЧОМУ НЕМАЄ ОКРЕМОГО ВИПАДКУ ДЛЯ ЗУМУ 1.0]
//
// Центр огляду ВІДСІКАЄТЬСЯ до меж світу: камера не може показати те, чого немає.
// При зумі 1.0 піввікна дорівнює півсвіту, тож відсікання притискає центр рівно до
// середини карти — і трансформація стає тотожною сама собою. Жодного if.
// ══════════════════════════════════════════════════════════════════════════

// cam — єдина камера виду зверху. Пакетна змінна, а не поле Game, свідомо: її читають
// тридцять точок малювання, і протягувати її параметром через кожну з них означало б
// зробити код гіршим заради формальної чистоти. Стан тут суто відображувальний —
// симуляція про камеру не знає нічого.
var cam = camera{zoom: camZoomMin, cx: screenWidth / 2, cy: screenHeight / 2}

type camera struct {
	zoom   float32 // 1.0 = увесь світ
	cx, cy float32 // центр огляду у СВІТОВИХ координатах
}

// follow — камера тягнеться за ціллю з тим самим ВІДСТАВАННЯМ, що вся анімація в грі.
// Різкий стрибок за гравцем різав би око, а лаг читається як інерція оператора.
func (c *camera) follow(tx, ty float32) {
	if c.zoom < camZoomMin {
		c.zoom = camZoomMin
	}
	halfW := float32(screenWidth) / 2 / c.zoom
	halfH := float32(screenHeight) / 2 / c.zoom
	c.cx += (clamp(tx, halfW, screenWidth-halfW) - c.cx) * camFollow
	c.cy += (clamp(ty, halfH, screenHeight-halfH) - c.cy) * camFollow
}

// px, py — світові координати в екранні. s — довжина/товщина/радіус.
func (c camera) px(wx float32) float32 { return (wx-c.cx)*c.zoom + screenWidth/2 }
func (c camera) py(wy float32) float32 { return (wy-c.cy)*c.zoom + screenHeight/2 }
func (c camera) s(v float32) float32   { return v * c.zoom }

// visible — чи потрапляє юніт у видиму область (із запасом на ворс і щупальце).
//
// При зумі 4× за кадром лишається 15/16 світу, і малювати їх усе одно означало б
// платити за те, чого не видно. Відсікання приходить разом із камерою задарма.
func (c camera) visible(wx, wy float32) bool {
	m := float32(pixelSize)*4 + furLen*furBristleLen // запас на найдовший ворс
	halfW := float32(screenWidth)/2/c.zoom + m
	halfH := float32(screenHeight)/2/c.zoom + m
	return wx > c.cx-halfW && wx < c.cx+halfW && wy > c.cy-halfH && wy < c.cy+halfH
}
